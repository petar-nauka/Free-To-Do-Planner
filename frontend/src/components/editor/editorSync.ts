/**
 * Решава дали входящият `content` prop да презапише текущото съдържание на редактора.
 *
 * Пропускаме синхронизацията, докато редакторът е ФОКУСИРАН (потребителят активно
 * пише или диктува). Иначе debounced auto-save → invalidate → refetch връща леко
 * остаряло съдържание, `setContent` пре-зарежда документа и НУЛИРА курсора по средата
 * на въвеждането — при диктовка с паузи това „откача" курсора и текстът спира да влиза.
 *
 * Когато редакторът НЕ е фокусиран (напр. смяна на бележка, първоначално зареждане),
 * синхронизираме нормално при реална промяна.
 */
export function shouldSyncEditorContent(
  isFocused: boolean,
  incoming: string,
  current: string,
): boolean {
  return !isFocused && incoming !== current;
}
