/**
 * Дълбоко копие на съдържание на програма.
 *
 * Нарочно през JSON, не `structuredClone`: съдържанието е чист JSON (така се пази и в
 * jsonb колоната), а JSON пътят работи и в по-стари браузъри, и в jsdom при тестовете.
 */
export function cloneContent(content: SportContent): SportContent {
  return JSON.parse(JSON.stringify(content)) as SportContent;
}

/** Ново копие на шаблона — за да не се мутира споделеният обект. */
export function freshSeedContent(): SportContent {
  return cloneContent(SPORT_PROGRAM_SEED);
}
